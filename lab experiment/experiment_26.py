import cv2
from google.colab import files

# Upload video
uploaded = files.upload()

video_name = next(iter(uploaded))

# Read input video
cap = cv2.VideoCapture(video_name)

frames = []

while True:
    ret, frame = cap.read()

    if not ret:
        break

    frames.append(frame)

cap.release()

# Check whether frames are available
if len(frames) == 0:
    print("Error: Video could not be read!")
else:
    height, width, _ = frames[0].shape

    fps = 25

    # Create reverse video
    out = cv2.VideoWriter(
        'reverse_video.mp4',
        cv2.VideoWriter_fourcc(*'mp4v'),
        fps,
        (width, height)
    )

    # Write frames in reverse order
    for frame in reversed(frames):
        out.write(frame)

    out.release()

    print("Reverse video created successfully!")

    # Download output video
    files.download('reverse_video.mp4')